// Renders the SQL forms of the variance-hold rules (variance.ts) that send_to_blast, the
// manager sign-off and the hold/blast views apply inside the database. Like release-sql.ts
// this is the only place that SQL is written: `pnpm --filter rules gen:sql` writes the
// migration, a rules test fails when the committed file is stale, and packages/db
// variance.db.test.ts checks the SQL agrees with variance.ts on a grid.
