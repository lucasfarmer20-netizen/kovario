function literal(value: string): string {
  return `'${value.replaceAll("'", "''")}'`;
}

function states(list: readonly string[]): string {
  return list.map(literal).join(", ");
}

export function renderVarianceSql(): string {
  const reasons = VARIANCE_SIGNOFF_REASONS.map(literal).join(", ");
  return [
    "-- GENERATED from packages/rules/src/variance-sql.ts — do not edit by hand.",
    "-- Regenerate with `pnpm --filter rules gen:sql`; a rules test fails when this is stale.",
    "-- Variance hold at reconcile (#87, docs/04-BUSINESS-RULES.md §6a, variance.ts):",
    "--   app.variance_pct                   — variancePercent (reconcile.ts);",
    "--   app.variance_band                  — varianceBand: within | near | over | unknown;",
    "--   app.format_variance                — formatVariance (refusal messages);",
    "--   app.variance_hold_group            — holdGroup over the rollstock sequence;",
    "--   app.variance_rollstock_window      — ROLLSTOCK_NEIGHBOUR_WINDOW_DAYS;",
    "--   app.variance_hold_limit            — varianceHoldLimit (org settings, with default);",
    "--   app.variance_hold_setting_problem  — varianceHoldSettingProblem;",
    "--   app.variance_signoff_problem       — varianceSignoffProblem;",
    "--   app.variance_hold_blocks           — holdBlocks (HOLD_BLOCKED_STATES);",
    "--   app.variance_actual_frozen         — actualFrozen (SENT_STATES);",
    "--   app.variance_member_keeps_open     — memberKeepsHoldOpen;",
    "--   public.variance_signoff_reason     — VARIANCE_SIGNOFF_REASONS.",
    "",
    "do $$ begin",
    `  create type public.variance_signoff_reason as enum (${reasons});`,
    "exception when duplicate_object then null; end $$;",
    "",
    "-- (actual − expected) / expected × 100, 2 decimals; null when nothing was expected.",
    "create or replace function app.variance_pct(p_actual numeric, p_expected numeric)",
    "returns numeric",
    "language sql",
    "immutable",
    "set search_path = ''",
    "as $$",
    "  select case when p_expected > 0 then round((p_actual - p_expected) / p_expected * 100, 2) end",
    "$$;",
    "",
    '-- "+14%", "−3.5%", "0%", "—": one decimal at most, halves away from zero, via hundredths.',
    "create or replace function app.format_variance(p_pct numeric)",
    "returns text",
    "language sql",
    "immutable",
    "set search_path = ''",
    "as $$",
    "  select case",
    `    when p_pct is null then ${literal(VARIANCE_NONE)}`,
    `    when t.tenths = 0 then ${literal(`0${VARIANCE_SUFFIX}`)}`,
    `    else case when p_pct > 0 then ${literal(VARIANCE_PLUS)} else ${literal(VARIANCE_MINUS)} end || trim_scale(t.tenths / 10)::text || ${literal(VARIANCE_SUFFIX)}`,
    "  end",
    "  from (select round(round(abs(p_pct) * 100) / 10) as tenths) t",
    "$$;",
    "",
    "-- Compared exactly at 2 decimals: |actual − expected| × 100 against limit × expected.",
    `-- Over the limit → over; at or past ${NEAR_LIMIT_NUMERATOR}/${NEAR_LIMIT_DENOMINATOR} of it → near; no expectation → unknown.`,
    "create or replace function app.variance_band(p_actual numeric, p_expected numeric, p_limit_pct int)",
    "returns text",
    "language plpgsql",
    "immutable",
    "set search_path = ''",
    "as $$",
    "declare",
    "  v_expected numeric;",
    "  v_off numeric;",
    "begin",
    `  if p_limit_pct is null or p_limit_pct < ${VARIANCE_HOLD_PCT_MIN} or p_limit_pct > ${VARIANCE_HOLD_PCT_MAX} then`,
    `    raise exception 'variance hold limit must be a whole percent ${VARIANCE_HOLD_PCT_MIN}–${VARIANCE_HOLD_PCT_MAX}' using errcode = '22023';`,
    "  end if;",
    "  if p_actual is null or p_expected is null or p_actual < 0 or p_expected < 0",
    "     or p_actual::text in ('NaN', 'Infinity') or p_expected::text in ('NaN', 'Infinity') then",
    "    raise exception 'weights must be finite and >= 0' using errcode = '22023';",
    "  end if;",
    "  v_expected := round(p_expected, 2);",
    "  if v_expected <= 0 then return 'unknown'; end if;",
    "  v_off := abs(round(p_actual, 2) - v_expected) * 100;",
    "  if v_off > p_limit_pct * v_expected then return 'over'; end if;",
    `  if v_off * ${NEAR_LIMIT_DENOMINATOR} >= ${NEAR_LIMIT_NUMERATOR} * p_limit_pct * v_expected then return 'near'; end if;`,
    "  return 'within';",
    "end;",
    "$$;",
    "",
    `-- ${HOLD_GROUP_BEFORE} before, the flagged intake, ${HOLD_GROUP_AFTER} after, clipped at either end; an`,
    "-- intake missing from the sequence is a group of one.",
    "create or replace function app.variance_hold_group(p_sequence uuid[], p_flagged uuid)",
    "returns uuid[]",
    "language sql",
    "immutable",
    "set search_path = ''",
    "as $$",
    "  select case when p.at is null then array[p_flagged]",
    `    else p_sequence[greatest(1, p.at - ${HOLD_GROUP_BEFORE}):p.at + ${HOLD_GROUP_AFTER}] end`,
    "  from (select array_position(p_sequence, p_flagged) as at) p",
    "$$;",
    "",
    "-- Neighbours are looked for among intakes opened within this of the flagged one.",
    "create or replace function app.variance_rollstock_window()",
    "returns interval",
    "language sql",
    "immutable",
    "set search_path = ''",
    "as $$",
    `  select interval '${ROLLSTOCK_NEIGHBOUR_WINDOW_DAYS} days'`,
    "$$;",
    "",
    "create or replace function app.variance_hold_limit(p_settings jsonb)",
    "returns int",
    "language sql",
    "immutable",
    "set search_path = ''",
    "as $$",
    `  select coalesce((p_settings #>> '{reconcile,variance_hold_pct}')::int, ${VARIANCE_HOLD_PCT_DEFAULT})`,
    "$$;",
    "",
    "-- settings.reconcile is optional; when present it is exactly {variance_hold_pct}.",
    "create or replace function app.variance_hold_setting_problem(p_settings jsonb)",
    "returns text",
    "language sql",
    "immutable",
    "set search_path = ''",
    "as $$",
    "  select case",
    "    when not (p_settings ? 'reconcile') then null",
    "    when jsonb_typeof(p_settings -> 'reconcile') <> 'object'",
    "      or app.json_keys(p_settings -> 'reconcile') <> array['variance_hold_pct']",
    `      or not app.json_int_between(p_settings #> '{reconcile,variance_hold_pct}', ${VARIANCE_HOLD_PCT_MIN}, ${VARIANCE_HOLD_PCT_MAX})`,
    `      then ${literal(VARIANCE_SETTING_PROBLEM)}`,
    "  end",
    "$$;",
    "",
    "create or replace function app.variance_signoff_problem(p_reason text, p_note text)",
    "returns text",
    "language sql",
    "immutable",
    "set search_path = ''",
    "as $$",
    "  select case",
    `    when p_reason is null or p_reason <> all (array[${reasons}]) then ${literal(SIGNOFF_UNKNOWN_REASON)}`,
    `    when length(coalesce(p_note, '')) > ${SIGNOFF_NOTE_MAX} then ${literal(SIGNOFF_NOTE_TOO_LONG)}`,
    `    when p_reason = 'other' and coalesce(p_note, '') !~ '\\S' then ${literal(SIGNOFF_OTHER_NEEDS_NOTE)}`,
    "  end",
    "$$;",
    "",
    "-- Not yet sent to blast: the states a hold blocks.",
    "create or replace function app.variance_hold_blocks(p_state public.intake_state)",
    "returns boolean",
    "language sql",
    "immutable",
    "set search_path = ''",
    "as $$",
    `  select p_state in (${states(HOLD_BLOCKED_STATES)})`,
    "$$;",
    "",
    "-- Sent to blast: the actual is the weight at Send to Blast.",
    "create or replace function app.variance_actual_frozen(p_state public.intake_state)",
    "returns boolean",
    "language sql",
    "immutable",
    "set search_path = ''",
    "as $$",
    `  select p_state in (${states(SENT_STATES)})`,
    "$$;",
    "",
    "-- A member keeps its hold open: not yet at reconcile, or at reconcile over the limit and not",
    "-- signed off at its current weight. Past reconcile and cancelled members are not judged.",
    "create or replace function app.variance_member_keeps_open(",
    "  p_state public.intake_state, p_band text, p_signed_off boolean",
    ")",
    "returns boolean",
    "language sql",
    "immutable",
    "set search_path = ''",
    "as $$",
    `  select p_state in (${states(AWAITING_RECONCILE_STATES)})`,
    "    or (p_state = 'reconcile' and p_band = 'over' and not coalesce(p_signed_off, false))",
    "$$;",
    "",
    "revoke all on function app.variance_pct(numeric, numeric),",
    "  app.variance_band(numeric, numeric, int), app.variance_hold_group(uuid[], uuid),",
    "  app.variance_hold_limit(jsonb), app.variance_hold_setting_problem(jsonb),",
    "  app.variance_signoff_problem(text, text), app.variance_rollstock_window(),",
    "  app.format_variance(numeric), app.variance_hold_blocks(public.intake_state),",
    "  app.variance_actual_frozen(public.intake_state),",
    "  app.variance_member_keeps_open(public.intake_state, text, boolean) from public;",
    "grant execute on function app.variance_pct(numeric, numeric),",
    "  app.variance_band(numeric, numeric, int), app.variance_hold_group(uuid[], uuid),",
    "  app.variance_hold_limit(jsonb), app.variance_rollstock_window(), app.format_variance(numeric),",
    "  app.variance_hold_blocks(public.intake_state), app.variance_actual_frozen(public.intake_state),",
    "  app.variance_member_keeps_open(public.intake_state, text, boolean) to authenticated, service_role;",
    "grant execute on function app.variance_hold_setting_problem(jsonb),",
    "  app.variance_signoff_problem(text, text) to service_role;",
    "",
  ].join("\n");
}

/** The SQL forms of holdWaitingOn's reason, holdWaitText, joinWaitTexts, holdWaitingMessage (#93). */
export function renderHoldWaitSql(): string {
  return [
    "-- GENERATED from packages/rules/src/variance-sql.ts — do not edit by hand.",
    "-- Regenerate with `pnpm --filter rules gen:sql`; a rules test fails when this is stale.",
    "-- What a variance hold waits on (#93, docs/08 DECISION-27, variance.ts):",
    "--   app.variance_hold_wait_text        — holdWaitingOn's reason + holdWaitText, one member;",
    "--   app.variance_hold_wait_list        — joinWaitTexts;",
    "--   app.variance_hold_waiting_message  — holdWaitingMessage.",
    "",
    '-- One member keeping the hold open: "INT-0003 (not at reconcile yet)", "INT-0004 (+22%)".',
    "create or replace function app.variance_hold_wait_text(",
    "  p_number text, p_state public.intake_state, p_actual numeric, p_variance_pct numeric",
    ")",
    "returns text",
    "language sql",
    "immutable",
    "set search_path = ''",
    "as $$",
    "  select p_number || ' (' || case",
    `    when p_state in (${states(AWAITING_RECONCILE_STATES)}) then ${literal(HOLD_WAIT_NOT_AT_RECONCILE)}`,
    `    when round(coalesce(p_actual, 0), 2) = 0 then ${literal(HOLD_WAIT_NOT_WEIGHED)}`,
    "    else app.format_variance(p_variance_pct)",
    "  end || ')'",
    "$$;",
    "",
    '-- "A", "A and B", "A, B and C".',
    "create or replace function app.variance_hold_wait_list(p_texts text[])",
    "returns text",
    "language sql",
    "immutable",
    "set search_path = ''",
    "as $$",
    "  select case when coalesce(cardinality(p_texts), 0) <= 1 then coalesce(p_texts[1], '')",
    "    else array_to_string(p_texts[1:cardinality(p_texts) - 1], ', ') || ' and '",
    "      || p_texts[cardinality(p_texts)]",
    "  end",
    "$$;",
    "",
    "-- Why an order whose own hold is active, though it is not over the limit, is refused; null",
    "-- when it is over (that refusal names its own variance).",
    "create or replace function app.variance_hold_waiting_message(p_number text, p_band text, p_waits text[])",
    "returns text",
    "language sql",
    "immutable",
    "set search_path = ''",
    "as $$",
    "  select case when p_band = 'over' then null else",
    "    p_number || ' ' || case when p_band = 'unknown'",
    `      then ${literal(HOLD_WAIT_NO_ESTIMATE)} else ${literal(HOLD_WAIT_WITHIN)} end || '.' ||`,
    `    case when coalesce(cardinality(p_waits), 0) = 0 then ${literal(` ${HOLD_WAIT_NOTHING_LEFT}`)}`,
    `      else ' Hold waits on ' || app.variance_hold_wait_list(p_waits) || ${literal(`. ${HOLD_WAIT_CLEARS}`)} end`,
    "  end",
    "$$;",
    "",
    "revoke all on function app.variance_hold_wait_text(text, public.intake_state, numeric, numeric),",
    "  app.variance_hold_wait_list(text[]), app.variance_hold_waiting_message(text, text, text[])",
    "  from public;",
    "grant execute on function app.variance_hold_wait_text(text, public.intake_state, numeric, numeric),",
    "  app.variance_hold_wait_list(text[]), app.variance_hold_waiting_message(text, text, text[])",
    "  to authenticated, service_role;",
    "",
  ].join("\n");
}

/** The SQL forms of holdJudgement and holdReevaluateOn (#95). */
export function renderHoldReevaluateSql(): string {
  return [
    "-- GENERATED from packages/rules/src/variance-sql.ts — do not edit by hand.",
    "-- Regenerate with `pnpm --filter rules gen:sql`; a rules test fails when this is stale.",
    "-- When a variance hold is re-evaluated (#95, docs/08 DECISION-27, variance.ts):",
    "--   app.variance_hold_judgement     — holdJudgement: awaiting | judged | not_judged;",
    "--   app.variance_hold_reevaluate_on — holdReevaluateOn (an intake state change).",
    "",
    "-- How a hold judges a member in this state.",
    "create or replace function app.variance_hold_judgement(p_state public.intake_state)",
    "returns text",
    "language sql",
    "immutable",
    "set search_path = ''",
    "as $$",
    `  select case when p_state in (${states(AWAITING_RECONCILE_STATES)}) then 'awaiting'`,
    "    when p_state = 'reconcile' then 'judged' else 'not_judged' end",
    "$$;",
    "",
    "-- A state change that can clear a hold the intake belongs to: it changes how the hold judges it.",
    "create or replace function app.variance_hold_reevaluate_on(",
    "  p_from public.intake_state, p_to public.intake_state",
    ")",
    "returns boolean",
    "language sql",
    "immutable",
    "set search_path = ''",
    "as $$",
    "  select app.variance_hold_judgement(p_from) <> app.variance_hold_judgement(p_to)",
    "$$;",
    "",
    "revoke all on function app.variance_hold_judgement(public.intake_state),",
    "  app.variance_hold_reevaluate_on(public.intake_state, public.intake_state) from public;",
    "grant execute on function app.variance_hold_judgement(public.intake_state),",
    "  app.variance_hold_reevaluate_on(public.intake_state, public.intake_state)",
    "  to authenticated, service_role;",
    "",
  ].join("\n");
}
